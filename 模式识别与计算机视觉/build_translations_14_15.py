def normalize_quotes(s: str) -> str:
    return (
        s.replace("\u2019", "'")
        .replace("\u2018", "'")
        .replace("\u201c", '"')
        .replace("\u201d", '"')
        .replace("\u2026", "...")
    )


def lookup(merged: dict, text: str):
    if text in merged:
        return merged[text]
    norm = normalize_quotes(text)
    if norm in merged:
        return merged[norm]
    return None


def should_skip(text: str) -> bool:
    t = text.strip()
    if not t:
        return True
    if re.search(r"[\u4e00-\u9fff]", t):
        return True
    if re.fullmatch(r"-?\d+(\.\d+)?", t):
        return True
    if len(t) == 1 and not t.isalpha():
        return True
    if re.fullmatch(r"[A-Za-z]", t):
        return True
    if re.search(r"[𝐹𝑈Σ𝑉𝑇𝑘]", t):
        return True
    if re.fullmatch(r"\([\d,\s\-]+\)", t):
        return True
    if t.startswith("http"):
        return True
    if t in "){,=-+*[{}":
        return True
    skip = {
        ").", "(2D", "F,", "E)", "RR", "= (", "= R", "= f/z'[x' y'",
        "=𝑈Σ", "=𝑘", "P=KR t", "rank 𝐹", "𝐹", "𝐹=𝑈Σ𝑉", "𝐹−𝐹", "𝑇", "𝑉",
        "1999.", "6.21", "54", "min", "e", "f", "p", "I", "J", "L", "H", "E", "T", "W",
        "x", "x'", "z'[", "z]", "z']", "[x y", "[x' y' z']", ", 0, 0)", "✓", "、",
        "3", "4", "2", "0", "1", "-1", "c", "_", "__",
    }
    if t in skip:
        return True
    return False


def build(texts, extra):
    merged = {**SHARED, **extra}
    result = {}
    for text in texts:
        if should_skip(text):
            continue
        zh = lookup(merged, text)
        if zh is not None and zh != text:
            result[text] = zh
        elif zh is not None and zh == text:
            # Keep identity mappings for citations/acronyms that must be in dict
            pass
    return result


def main():
    for num, extra in [(14, {}), (15, PDF15)]:
        texts = json.loads((BASE / f"{num}_texts.json").read_text(encoding="utf-8"))
        trans = build(texts, extra)
        out = BASE / f"{num}_translations.json"
        out.write_text(json.dumps(trans, ensure_ascii=False, indent=2), encoding="utf-8")
        untrans = [t for t in texts if not should_skip(t) and t not in trans]
        print(f"PDF {num}: entries={len(trans)}, untranslated={len(untrans)}")
        if untrans:
            print("  Missing:", untrans)


