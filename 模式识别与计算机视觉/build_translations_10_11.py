def should_skip(text: str) -> bool:
    t = text.strip()
    if not t:
        return True
    if re.search(r"[\u4e00-\u9fff]", t):
        return True
    if re.fullmatch(r"-?\d+(\.\d+)?", t):
        return True
    if len(t) == 1 and not t.isalpha():
        return True
    if re.fullmatch(r"[A-Za-z]", t):
        return True
    if t in {"2D", "3D", "2026", "SVD", "DLT", "RANSAC", "DEF.", "PP1", "PP2", "PP3",
             "Laplacian", "jet", "Word/LaTeX", "(DLT)", "(RANSAC)"}:
        return True
    if re.fullmatch(r"[\d\s\.\?=\-/\\]+", t):
        return True
    if t in {"N,", "N, =6", "\u22c5P"}:
        return True
    if t.startswith("rotation(θ)"):
        return True
    if t.startswith("2.1") and "4.2" in t:
        return True
    if t.startswith("nju_"):
        return True
    skip = {",t", "=>", "= H", "=0", "=14", "p, at", "A;h", ". P", "2n x", "f(ar)", "a I", "a", "o", "p=0.99)"}
    if t in skip:
        return True
    return False


def build(texts, extra):
    merged = {**SHARED, **extra}
    result = {}
    for text in texts:
        if should_skip(text):
            continue
        if text in merged and merged[text] != text:
            result[text] = merged[text]
    return result


def main():
    for num, extra in [(10, PDF10), (11, PDF11)]:
        texts = json.loads((BASE / f"{num}_texts.json").read_text(encoding="utf-8"))
        trans = build(texts, extra)
        out = BASE / f"{num}_translations.json"
        out.write_text(json.dumps(trans, ensure_ascii=False, indent=2), encoding="utf-8")
        untrans = [t for t in texts if not should_skip(t) and t not in trans]
        print(f"PDF {num}: entries={len(trans)}, untranslated={len(untrans)}")
        if untrans:
            print("  Missing:", untrans[:30])


if __name__ == "__main__":
    main()
